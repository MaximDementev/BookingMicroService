namespace Domain.Enums
{
    using System.Runtime.Serialization;

    /// <summary>
    /// Представляет возможные статусы бронирования в системе.
    /// </summary>
    public enum BookingStatus
    {
        /// <summary>
        /// Черновик.
        /// Бронирование только создается пользователем, места или билеты могут быть временно заблокированы, 
        /// но процесс оформления еще не запущен. Личные данные могут быть заполнены частично.
        /// </summary>
        [EnumMember(Value = "draft")]
        Draft,

        /// <summary>
        /// В процессе оформления и покупки.
        /// Ожидается подтверждение платежной системы или внешнего поставщика. 
        /// Места зафиксированы за пользователем на время тикет-тайма (окна оплаты).
        /// </summary>
        [EnumMember(Value = "pending")]
        Pending,

        /// <summary>
        /// Бронирование оплачено.
        /// Деньги успешно списаны, бронь подтверждена. На этом этапе обычно генерируются 
        /// и выпускаются сами электронные билеты (переходят в статус Active).
        /// </summary>
        [EnumMember(Value = "paid")]
        Paid,

        /// <summary>
        /// Покупка отменена.
        /// Бронирование аннулировано до момента оплаты (например, истекло время ожидания платежа 
        /// или пользователь сам нажал кнопку «Отмена» на этапе Pending/Draft). Деньги не списывались.
        /// </summary>
        [EnumMember(Value = "cancelled")]
        Cancelled,

        /// <summary>
        /// Деньги возвращены.
        /// Возврат уже оплаченного бронирования (Paid). Запущена процедура чарджбэка/возврата средств 
        /// на карту клиента. Связанные билеты аннулируются.
        /// </summary>
        [EnumMember(Value = "refunded")]
        Refunded
    }

}