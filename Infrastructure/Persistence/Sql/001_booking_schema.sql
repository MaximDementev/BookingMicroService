CREATE TABLE bookings (
    booking_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL,
    offer_id bigint NOT NULL,
    supplier_id varchar(100) NOT NULL,
    provider_offer_id varchar(255) NOT NULL,
    booking_code varchar(50) NOT NULL,
    create_idempotency_key varchar(100) NOT NULL,
    booking_status varchar(32) NOT NULL,
    payment_status varchar(32) NOT NULL,
    issuance_status varchar(32) NOT NULL,
    total_amount numeric(18,2) NOT NULL,
    currency varchar(3) NOT NULL,
    contact_email varchar(254) NOT NULL,
    contact_phone varchar(32),
    payment_id bigint,
    offer_expires_at timestamptz,
    paid_at timestamptz,
    completed_at timestamptz,
    version bigint NOT NULL,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (booking_id, supplier_id),
    CONSTRAINT ck_booking_money CHECK (total_amount >= 0 AND currency ~ '^[A-Z]{3}$'),
    CONSTRAINT ck_booking_owner CHECK (user_id > 0 AND offer_id > 0),
    CONSTRAINT ck_booking_code CHECK (length(btrim(booking_code)) > 0 AND length(btrim(create_idempotency_key)) > 0),
    CONSTRAINT ck_booking_status CHECK (booking_status IN ('Draft','Pending','Paid','Completed','PartiallyCompleted','Expired','Cancelled','Refunded','RequiresReview')),
    CONSTRAINT ck_payment_status CHECK (payment_status IN ('NotStarted','Pending','Succeeded','Failed','RefundPending','PartiallyRefunded','Refunded','Unknown')),
    CONSTRAINT ck_issuance_status CHECK (issuance_status IN ('NotStarted','Pending','Issued','PartiallyIssued','Rejected','Unknown'))
);
CREATE UNIQUE INDEX ux_booking_code ON bookings(booking_code);
CREATE UNIQUE INDEX ux_booking_creation ON bookings(user_id, create_idempotency_key);

CREATE TABLE booking_passengers (
    booking_passenger_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id bigint NOT NULL REFERENCES bookings(booking_id) ON DELETE RESTRICT,
    source_passenger_id bigint,
    first_name varchar(100) NOT NULL,
    last_name varchar(100) NOT NULL,
    middle_name varchar(100),
    date_of_birth date NOT NULL,
    gender varchar(32) NOT NULL,
    citizenship_code varchar(3) NOT NULL,
    document_type varchar(32) NOT NULL,
    document_number_encrypted text NOT NULL,
    document_issuing_country varchar(3) NOT NULL,
    document_expires_at date,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (booking_passenger_id, booking_id)
);
CREATE INDEX ix_passenger_booking ON booking_passengers(booking_id);

CREATE TABLE booking_routes (
    booking_route_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id bigint NOT NULL REFERENCES bookings(booking_id) ON DELETE RESTRICT,
    sequence_number integer NOT NULL,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (booking_route_id, booking_id),
    CONSTRAINT ck_route_sequence CHECK (sequence_number > 0)
);
CREATE UNIQUE INDEX ux_route_sequence ON booking_routes(booking_id,sequence_number);

CREATE TABLE booking_flights (
    booking_flight_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id bigint NOT NULL,
    booking_route_id bigint NOT NULL,
    source_flight_id bigint,
    provider_segment_id varchar(255) NOT NULL,
    sequence_number integer NOT NULL,
    departure_airport varchar(3) NOT NULL,
    arrival_airport varchar(3) NOT NULL,
    departure_at timestamptz NOT NULL,
    arrival_at timestamptz NOT NULL,
    departure_time_zone varchar(100),
    arrival_time_zone varchar(100),
    airline_code varchar(10) NOT NULL,
    flight_number varchar(20) NOT NULL,
    aircraft_code varchar(10),
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (booking_flight_id,booking_id,booking_route_id),
    FOREIGN KEY (booking_route_id,booking_id) REFERENCES booking_routes(booking_route_id,booking_id) ON DELETE RESTRICT,
    CONSTRAINT ck_flight_sequence CHECK (sequence_number > 0),
    CONSTRAINT ck_flight_time CHECK (arrival_at > departure_at)
);
CREATE UNIQUE INDEX ux_flight_sequence ON booking_flights(booking_route_id,sequence_number);
CREATE UNIQUE INDEX ux_provider_segment ON booking_flights(booking_id,provider_segment_id);
CREATE INDEX ix_flight_route_booking ON booking_flights(booking_route_id,booking_id);

CREATE TABLE booking_items (
    booking_item_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id bigint NOT NULL,
    booking_passenger_id bigint NOT NULL,
    booking_route_id bigint NOT NULL,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (booking_item_id,booking_id,booking_route_id),
    FOREIGN KEY (booking_passenger_id,booking_id) REFERENCES booking_passengers(booking_passenger_id,booking_id) ON DELETE RESTRICT,
    FOREIGN KEY (booking_route_id,booking_id) REFERENCES booking_routes(booking_route_id,booking_id) ON DELETE RESTRICT
);
CREATE UNIQUE INDEX ux_item_passenger_route ON booking_items(booking_passenger_id,booking_route_id);
CREATE INDEX ix_item_passenger_booking ON booking_items(booking_passenger_id,booking_id);
CREATE INDEX ix_item_route_booking ON booking_items(booking_route_id,booking_id);

CREATE TABLE reservations (
    reservation_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id bigint NOT NULL,
    supplier_id varchar(100) NOT NULL,
    idempotency_key varchar(100) NOT NULL,
    provider_booking_id varchar(255),
    provider_booking_reference varchar(100),
    status varchar(32) NOT NULL,
    reserved_at timestamptz,
    confirmed_at timestamptz,
    expires_at timestamptz,
    total_price_amount numeric(18,2),
    total_price_currency varchar(3),
    error_code varchar(100),
    version bigint NOT NULL,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (reservation_id,booking_id),
    FOREIGN KEY (booking_id,supplier_id) REFERENCES bookings(booking_id,supplier_id) ON DELETE RESTRICT,
    CONSTRAINT ck_reservation_status CHECK (status IN ('Pending','Confirmed','Rejected','Expired','Cancelled','Unknown')),
    CONSTRAINT ck_reservation_money CHECK ((total_price_amount IS NULL AND total_price_currency IS NULL) OR (total_price_amount IS NOT NULL AND total_price_currency IS NOT NULL AND total_price_amount >= 0 AND total_price_currency ~ '^[A-Z]{3}$')),
    CONSTRAINT ck_reservation_key CHECK (length(btrim(idempotency_key)) > 0),
    CONSTRAINT ck_confirmed_reservation CHECK (status <> 'Confirmed' OR (provider_booking_id IS NOT NULL AND confirmed_at IS NOT NULL AND expires_at IS NOT NULL AND total_price_amount IS NOT NULL))
);
CREATE UNIQUE INDEX ux_reservation_operation ON reservations(booking_id,idempotency_key);
CREATE UNIQUE INDEX ux_provider_booking ON reservations(supplier_id,provider_booking_id);
CREATE INDEX ix_reservation_expiry ON reservations(status,expires_at);
CREATE INDEX ix_reservation_supplier ON reservations(booking_id,supplier_id);

CREATE TABLE reservation_passengers (
    reservation_passenger_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id bigint NOT NULL,
    reservation_id bigint NOT NULL,
    booking_passenger_id bigint NOT NULL,
    provider_passenger_id varchar(255) NOT NULL,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (reservation_id,booking_id) REFERENCES reservations(reservation_id,booking_id) ON DELETE RESTRICT,
    FOREIGN KEY (booking_passenger_id,booking_id) REFERENCES booking_passengers(booking_passenger_id,booking_id) ON DELETE RESTRICT
);
CREATE UNIQUE INDEX ux_reservation_passenger ON reservation_passengers(reservation_id,booking_passenger_id);
CREATE UNIQUE INDEX ux_provider_passenger ON reservation_passengers(reservation_id,provider_passenger_id);
CREATE INDEX ix_reservation_passenger_booking ON reservation_passengers(reservation_id,booking_id);
CREATE INDEX ix_reservation_passenger_owner ON reservation_passengers(booking_passenger_id,booking_id);

CREATE TABLE e_tickets (
    e_ticket_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id bigint NOT NULL,
    booking_item_id bigint NOT NULL,
    booking_route_id bigint NOT NULL,
    reservation_id bigint NOT NULL,
    ticket_number varchar(50) NOT NULL,
    issuer_code varchar(100) NOT NULL,
    status varchar(32) NOT NULL,
    price_amount numeric(18,2) NOT NULL,
    price_currency varchar(3) NOT NULL,
    issued_at timestamptz NOT NULL,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (e_ticket_id,booking_id,booking_route_id),
    FOREIGN KEY (booking_item_id,booking_id,booking_route_id) REFERENCES booking_items(booking_item_id,booking_id,booking_route_id) ON DELETE RESTRICT,
    FOREIGN KEY (reservation_id,booking_id) REFERENCES reservations(reservation_id,booking_id) ON DELETE RESTRICT,
    CONSTRAINT ck_ticket_status CHECK (status IN ('Active','Used','Void','Refunded')),
    CONSTRAINT ck_ticket_money CHECK (price_amount >= 0 AND price_currency ~ '^[A-Z]{3}$'),
    CONSTRAINT ck_ticket_number CHECK (length(btrim(ticket_number)) > 0 AND length(btrim(issuer_code)) > 0)
);
CREATE UNIQUE INDEX ux_ticket_number ON e_tickets(issuer_code,ticket_number);
CREATE INDEX ix_ticket_item ON e_tickets(booking_item_id,booking_id,booking_route_id);
CREATE INDEX ix_ticket_reservation ON e_tickets(reservation_id,booking_id);

CREATE TABLE e_ticket_segments (
    e_ticket_segment_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id bigint NOT NULL,
    booking_route_id bigint NOT NULL,
    e_ticket_id bigint NOT NULL,
    booking_flight_id bigint NOT NULL,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (e_ticket_id,booking_id,booking_route_id) REFERENCES e_tickets(e_ticket_id,booking_id,booking_route_id) ON DELETE RESTRICT,
    FOREIGN KEY (booking_flight_id,booking_id,booking_route_id) REFERENCES booking_flights(booking_flight_id,booking_id,booking_route_id) ON DELETE RESTRICT
);
CREATE UNIQUE INDEX ux_ticket_segment ON e_ticket_segments(e_ticket_id,booking_flight_id);
CREATE INDEX ix_segment_ticket ON e_ticket_segments(e_ticket_id,booking_id,booking_route_id);
CREATE INDEX ix_segment_flight ON e_ticket_segments(booking_flight_id,booking_id,booking_route_id);

CREATE TABLE inbox_messages (
    inbox_message_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source varchar(100) NOT NULL,
    external_message_id varchar(255) NOT NULL,
    processed_at timestamptz NOT NULL,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX ux_inbox_message ON inbox_messages(source,external_message_id);

CREATE TABLE outbox_messages (
    outbox_message_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id bigint NOT NULL REFERENCES bookings(booking_id) ON DELETE RESTRICT,
    message_type varchar(255) NOT NULL,
    payload jsonb NOT NULL,
    occurred_at timestamptz NOT NULL,
    published_at timestamptz,
    attempts integer NOT NULL,
    last_error varchar(2000),
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_outbox_attempts CHECK (attempts >= 0)
);
CREATE INDEX ix_outbox_unpublished ON outbox_messages(published_at,outbox_message_id) WHERE published_at IS NULL;
CREATE INDEX ix_outbox_booking ON outbox_messages(booking_id);
